def to_bits(data):
    return "".join(f"{b:08b}" for b in data)

def to_hex(bits):
    return f"{int(bits, 2):0{len(bits) // 4}X}"

def permute(bits, table):
    return "".join(bits[i - 1] for i in table)

def xor(a, b):
    return "".join("0" if x == y else "1" for x, y in zip(a, b))


def subkeys(key):

    k = permute(to_bits(key), PC1)
    c, d = k[:28], k[28:]
    keys = []
    for n in SHIFTS:
        # 48 bit round key
        c = c[n:] + c[:n]
        d = d[n:] + d[:n]
        keys.append(permute(c + d, PC2))
    return keys


def sboxes(bits48):
    # groups of 6 bits
    out = ""
    for i in range(8):
        b = bits48[i * 6:i * 6 + 6]
        row = int(b[0] + b[5], 2)
        col = int(b[1:5], 2)
        out += f"{S[i][row][col]:04b}"
    return out


def des_round(L, R, K):
    expanded = permute(R, E)
    mixed = xor(expanded, K)
    f = permute(sboxes(mixed), P)
    return R, xor(L, f)


def des_block(block, key, decrypt=False):
    #enc or dec 
    keys = subkeys(key)
    if decrypt:
        keys.reverse()   
    bits = permute(to_bits(block), IP)
    L, R = bits[:32], bits[32:]
    for K in keys:
        L, R = des_round(L, R, K)
    out = permute(R + L, FP)
    return bytes.fromhex(to_hex(out))


def ecb_encrypt(data, key=KEY):
    n = 8 - len(data) % 8
    data += bytes([n] * n)
    result = b""
    for i in range(0, len(data), 8):
        result += des_block(data[i:i + 8], key)
    return result


def ecb_decrypt(data, key=KEY):
    result = b""
    for i in range(0, len(data), 8):
        result += des_block(data[i:i + 8], key, decrypt=True)
    return result[:-result[-1]]


def show_blocks(data):
    return " | ".join(data[i:i + 8].hex().upper() for i in range(0, len(data), 8))
